"""Bundle grader/ + local/api.py into one file, dist/fallfest.py, that a
notebook can download and import. Run: python local/build.py"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
MODULES = ["core", "assets", "beginner", "advanced", "registry"]

parts = ['"""Qiskit Fall Fest 2026 grader (single-file build). Generated by local/build.py; edit grader/ instead."""',
         "import sys as _sys, types as _types",
         "_SOURCES = {"]
for m in MODULES:
    parts.append(f"    {m!r}: {(ROOT / 'grader' / f'{m}.py').read_text()!r},")
parts.append("}")
parts.append('''
_pkg = _types.ModuleType("_ffgrader")
_pkg.__path__ = []
_sys.modules["_ffgrader"] = _pkg
for _name in ''' + repr(MODULES) + ''':
    _mod = _types.ModuleType("_ffgrader." + _name)
    _mod.__package__ = "_ffgrader"
    _mod.__file__ = "<fallfest:" + _name + ">"
    _sys.modules[_mod.__name__] = _mod
    setattr(_pkg, _name, _mod)
    exec(compile(_SOURCES[_name], _mod.__file__, "exec"), _mod.__dict__)
''')
parts.append((ROOT / "local" / "api.py").read_text())
out = ROOT / "dist" / "fallfest.py"
out.parent.mkdir(exist_ok=True)
out.write_text("\n".join(parts))
print(f"wrote {out} ({out.stat().st_size // 1024} KB)")
